#!/usr/bin/env python3
"""Export every canonical file widget for manual MainUI import without reformatting."""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "openHAB/yaml/widgets"
OUTPUT_DIR = ROOT / "openHAB/mainui/widgets"
HEADER = "# Generated by tools/export_openhab_widget.py; edit the canonical source.\n"


def render(source):
    """Split the file wrapper into one native MainUI definition per widget UID."""
    wrapper = "version: 1\nwidgets:\n"
    if not source.startswith(wrapper):
        raise ValueError("Expected a version-1 widgets file")
    result, body, uid = {}, [], None

    def finish():
        if uid is not None:
            if not any(line.strip() for line in body):
                raise ValueError("Expected a nonempty widget body")
            result[uid] = HEADER + f"uid: {uid}\n" + "".join(body)

    for line in source[len(wrapper) :].splitlines(keepends=True):
        key = re.fullmatch(r"  ([A-Za-z0-9_-]+):\n?", line)
        if key:
            finish()
            uid, body = key[1], []
            if uid in result:
                raise ValueError("Duplicate widget UID")
        elif uid is None:
            if line.strip():
                raise ValueError("Expected a widget UID")
        elif line.strip() and not line.startswith("    "):
            raise ValueError("Expected widget contents indented by four spaces")
        else:
            body.append(line[4:] if line.startswith("    ") else line)
    finish()
    if not result:
        raise ValueError("Expected at least one widget")
    return result


def exports(directory):
    """Collect all outputs before writing so duplicate UIDs cannot overwrite a widget."""
    result = {}
    paths = sorted([*directory.glob("*.yml"), *directory.glob("*.yaml")])
    for path in paths:
        widgets = render(path.read_text(encoding="utf-8"))
        if result.keys() & widgets.keys():
            raise ValueError("Duplicate widget UID across source files")
        result.update(widgets)
    if not result:
        raise ValueError("No canonical widget sources found")
    return {uid + ".yaml": content for uid, content in result.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if any MainUI export is stale")
    args = parser.parse_args()
    try:
        expected = exports(SOURCE_DIR)
        if args.check:
            actual = {p.name for p in OUTPUT_DIR.glob("*.yaml")} | {
                p.name for p in OUTPUT_DIR.glob("*.yml")
            }
            if actual != expected.keys() or any(
                (OUTPUT_DIR / name).read_text(encoding="utf-8") != content
                for name, content in expected.items()
            ):
                print(
                    "Widget exports are stale; run python3 tools/export_openhab_widget.py "
                    "and remove obsolete generated exports",
                    file=sys.stderr,
                )
                return 1
            print(f"All {len(expected)} MainUI exports match the canonical sources.")
        else:
            OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
            for name, content in expected.items():
                target = OUTPUT_DIR / name
                target.write_text(content, encoding="utf-8")
                print(f"Generated {target.relative_to(ROOT)}")
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Cannot export widgets: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
